#!/usr/bin/env node
/*
 * Builds the generated parts of the root README.md from each example's example.json:
 *
 *   node scripts/build-readme.mjs            rewrite the catalog between the catalog markers
 *   node scripts/build-readme.mjs --check    exit 1 when the catalog is out of date (validate.mjs runs this)
 *   node scripts/build-readme.mjs --mosaic   also rebuild the header pictures (needs ImageMagick's `magick`)
 *
 * The catalog lists every example under its topic, each topic heading linking to its runmat.com page. FEA
 * studies are grouped by the simulation page they come from. The header pictures are a mosaic of the examples'
 * own thumbnails (MOSAIC below), one for GitHub's dark theme and one for its light theme.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const README = join(ROOT, "README.md");
const SITE = "https://runmat.com";
const START = "<!-- catalog:start (generated by scripts/build-readme.mjs; do not edit by hand) -->";
const END = "<!-- catalog:end -->";

/** Topic order in the catalog: simulation first, then industries, then math topics. */
const ORDER = [
  "fea",
  "aerospace",
  "automotive-transportation",
  "construction",
  "defense",
  "electronics-semiconductors",
  "energy",
  "industrial-machinery",
  "life-sciences",
  "quant",
  "plotting",
  "signal-processing",
  "statistics",
  "curve-fitting",
  "data-tables",
  "differential-equations",
  "linear-algebra",
  "optimization",
  "control-systems",
  "finance",
];

/** A topic whose examples don't name a runmat.com page of their own. */
const TOPIC_PAGE = { construction: "/cad", fea: "/simulation" };

/** FEA groups, by the simulation page an example comes from. Others fall under "More studies". */
const FEA_GROUPS = [
  ["/simulation/structural", "Structural"],
  ["/simulation/thermal", "Thermal"],
  ["/simulation/thermomechanical", "Thermomechanical"],
  ["/simulation/conjugate-heat-transfer", "Conjugate heat transfer"],
  ["/simulation/fluid-flow", "Fluid flow"],
  ["/simulation/fluid-structure", "Fluid-structure"],
  ["/simulation/electromagnetic", "Electromagnetic"],
  ["/simulation/electrothermal", "Electrothermal"],
  ["/simulation/acoustics", "Acoustics"],
];

/** The header mosaic: the first tile spans two columns and two rows; the rest fill a 4 x 3 grid around it. */
const MOSAIC = [
  "aerospace/airliner",
  "aerospace/camera-drone",
  "construction/house",
  "fea/bracket-hook-load",
  "fea/six-bolt-busbar",
  "plotting/damped-radial-wave",
  "defense/multi-drone-slam",
  "fea/heat-spreader-warm-up",
  "signal-processing/run-up-spectrogram",
];

const isDir = (path) => existsSync(path) && statSync(path).isDirectory();

function examples() {
  const found = [];
  for (const group of readdirSync(ROOT).sort()) {
    if (group.startsWith(".") || ["scripts", "node_modules"].includes(group) || !isDir(join(ROOT, group))) continue;
    for (const name of readdirSync(join(ROOT, group)).sort()) {
      const record = join(ROOT, group, name, "example.json");
      if (!existsSync(record)) continue;
      found.push({ path: `${group}/${name}`, ...JSON.parse(readFileSync(record, "utf8")) });
    }
  }
  return found;
}

const kindNote = (example) => (example.kind === "design" ? " (design project)" : "");
const row = (example) => `- [${example.title}](${example.path})${kindNote(example)}: ${example.line}`;

function catalog(all) {
  const byTopic = new Map();
  for (const example of all) {
    if (!byTopic.has(example.topic)) byTopic.set(example.topic, []);
    byTopic.get(example.topic).push(example);
  }
  const unknown = [...byTopic.keys()].filter((topic) => !ORDER.includes(topic));
  if (unknown.length) throw new Error(`topics missing from ORDER in build-readme.mjs: ${unknown.join(", ")}`);
  const sections = [];
  for (const topic of ORDER) {
    const items = (byTopic.get(topic) ?? []).sort((a, b) => a.title.localeCompare(b.title));
    if (!items.length) continue;
    const label = items[0].topicLabel ?? topic;
    const page = TOPIC_PAGE[topic] ?? items.map((e) => e.origin?.page).find((p) => p?.startsWith("/") && p !== "/");
    const heading = page ? `### [${label}](${SITE}${page})` : `### ${label}`;
    const lines = [heading, ""];
    if (topic === "fea") {
      const grouped = new Map(FEA_GROUPS.map(([path]) => [path, []]));
      const more = [];
      for (const example of items) (grouped.get(example.origin?.page) ?? more).push(example);
      for (const [path, name] of FEA_GROUPS) {
        const group = grouped.get(path);
        if (!group.length) continue;
        lines.push(`**[${name}](${SITE}${path})**`, "", ...group.map(row), "");
      }
      if (more.length) lines.push("**More studies**", "", ...more.map(row), "");
    } else {
      lines.push(...items.map(row), "");
    }
    sections.push(lines.join("\n").trimEnd());
  }
  const counts = { script: 0, study: 0, design: 0 };
  for (const example of all) counts[example.kind] = (counts[example.kind] ?? 0) + 1;
  const summary = `${all.length} examples: ${counts.script} scripts, ${counts.study} FEA studies and ${counts.design} design projects.`;
  return [START, "", summary, "", sections.join("\n\n"), "", END].join("\n");
}

function mosaic() {
  const out = join(ROOT, ".github", "readme");
  mkdirSync(out, { recursive: true });
  const W = 480;
  const H = 270;
  const GAP = 6;
  const cell = (col, row) => [col * (W + GAP), row * (H + GAP)];
  const slots = [cell(2, 0), cell(3, 0), cell(2, 1), cell(3, 1), cell(0, 2), cell(1, 2), cell(2, 2), cell(3, 2)];
  const width = 4 * W + 3 * GAP;
  const height = 3 * H + 2 * GAP;
  for (const [theme, file, background] of [
    ["dark", "thumbnail.webp", "#0d1117"],
    ["light", "thumbnail.light.webp", "#ffffff"],
  ]) {
    const thumb = (path) => {
      const themed = join(ROOT, path, ".artifacts", file);
      if (!existsSync(themed)) throw new Error(`${path} has no ${file} for the ${theme} mosaic`);
      return themed;
    };
    const args = ["-size", `${width}x${height}`, `xc:${background}`];
    const [feature, ...rest] = MOSAIC;
    args.push("(", thumb(feature), "-resize", `${2 * W + GAP}x${2 * H + GAP}^`, "-gravity", "center", "-extent", `${2 * W + GAP}x${2 * H + GAP}`, ")");
    args.push("-gravity", "northwest", "-geometry", "+0+0", "-composite");
    rest.forEach((path, index) => {
      const [x, y] = slots[index];
      args.push("(", thumb(path), "-resize", `${W}x${H}^`, "-gravity", "center", "-extent", `${W}x${H}`, ")");
      args.push("-gravity", "northwest", "-geometry", `+${x}+${y}`, "-composite");
    });
    args.push("-quality", "86", join(out, `examples-${theme}.webp`));
    execFileSync("magick", args, { stdio: "inherit" });
  }
}

const args = process.argv.slice(2);
const readme = readFileSync(README, "utf8");
const start = readme.indexOf(START);
const end = readme.indexOf(END);
if (start < 0 || end < start) {
  console.error(`README.md has no catalog markers (${START} ... ${END})`);
  process.exit(1);
}
const next = readme.slice(0, start) + catalog(examples()) + readme.slice(end + END.length);
if (args.includes("--check")) {
  if (next !== readme) {
    console.error("README.md catalog is out of date: run node scripts/build-readme.mjs");
    process.exit(1);
  }
  process.exit(0);
}
if (args.includes("--mosaic")) mosaic();
if (next !== readme) writeFileSync(README, next);
console.log("README.md catalog up to date");
